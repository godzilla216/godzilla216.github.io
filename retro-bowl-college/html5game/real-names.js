    function resolve(kind, uid, field, value) {
        var entry = data[kind] && data[kind][Number(uid)];
        var change = entry && entry[field];
        // The native editor rebuilds final titles from subdivision/conference names.
        // Recognize its default generated titles as well as the original file labels.
        if (kind === 'competitions' && field === 'name' && change) {
            var id = Number(uid);
            if (id >= 1000 && id <= 3000 && id % 1000 === 0 && value === 'FBS Championship') return change[1];
            var conferenceId = [3,14,5,4,6,8,13,10,11,12][id - 6000];
            var conference = data.conferences[conferenceId];
            if (conference && (value === conference.name[0] + ' Championship' || value === conference.name[1] + ' Championship')) return change[1];
        }
        return change && value === change[0] ? change[1] : value;
    }
    function struct(kind, item) {
        if (!item || typeof item !== 'object') return;
        var entry = data[kind][Number(item.gmluid)];
        if (entry) Object.keys(entry).forEach(function(field) {
            item['gml' + field] = resolve(kind, item.gmluid, field, item['gml' + field]);
        });
    }
    function teamMap(map) {
        var uid = ds_map_find_value(map, 'uid');
        ['name','tla'].forEach(function(field) {
            var old = ds_map_find_value(map, field), value = resolve('teams', uid, field, old);
            if (value !== old) ds_map_set(map, field, value);
        });
    }
    function apply(master) {
        if (!master || !master.gmlco_mode) return;
        if (typeof master.gmlteamlist === 'number' && ds_exists(master.gmlteamlist, 2)) {
            for (var i = 0; i < ds_list_size(master.gmlteamlist); i++) teamMap(ds_list_find_value(master.gmlteamlist,i));
        }
        (master.gmlconferences || []).forEach(function(item) { struct('conferences',item); });
        (master.gmlcompetitions || []).forEach(function(item) { struct('competitions',item); });
        var custom = master.gmlcustom_data;
        if (custom && typeof custom === 'object') {
            (custom.gmlconferences || []).forEach(function(item) { struct('conferences',item); });
            (custom.gmlcompetitions || []).forEach(function(item) { struct('competitions',item); });
            (custom.gmlsubdivisions || []).forEach(function(item,i) {
                if (item && /^(MAJOR|Major|MINOR|Minor)$/.test(item.gmlname)) item.gmlname = i === 1 ? 'FBS' : 'FCS';
            });
        }
    }
    // The original columns were designed for 12-character school names.
    // Keep complete real names readable inside those columns.
    var widths = Object.create(null);
    Object.keys(data.teams).forEach(function(id) { widths[data.teams[id].name[1].toUpperCase()] = 96; });
    Object.keys(data.conferences).forEach(function(id) {
        ['name','div_0_name','div_1_name'].forEach(function(field) {
            var key = data.conferences[id][field][1].toUpperCase();
            if (!widths[key]) widths[key] = 112;
        });
    });
    Object.keys(data.competitions).forEach(function(id) {
        var key = data.competitions[id].name[1].toUpperCase();
        if (!widths[key]) widths[key] = Number(id) < 1000 ? 112 : 192;
    });
    function textScale(value, measuredWidth) {
        var width = typeof value === 'string' && widths[value.toUpperCase()];
        return width && measuredWidth > width ? width / measuredWidth : 1;
    }
    function widthLimit(value) {
        return typeof value === 'string' && widths[value.toUpperCase()] || 0;
    }
    return {data:data, resolve:resolve, apply:apply, teamMap:teamMap, textScale:textScale, widthLimit:widthLimit};

